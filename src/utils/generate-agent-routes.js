import { promises as fs } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { getSiteRoutes, STATIC_PATHS } from "./site-routes.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const OUTPUT = path.join(__dirname, "agent-routes.generated.js");

const generate = async () => {
  const { coursePages, provinciaPages } = await getSiteRoutes();

  const content = `// Auto-generated by generate-agent-routes.js — do not edit manually.
// Regenerated on every build (see vite.config.js prebuild hooks).

export const GENERATED_AT = ${JSON.stringify(
    new Date().toISOString().slice(0, 10)
  )};

export const STATIC_ROUTES = ${JSON.stringify(STATIC_PATHS)};

export const COURSE_PATHS = ${JSON.stringify(
    coursePages.map(({ path }) => path)
  )};

export const PROVINCIA_PATHS = ${JSON.stringify(
    provinciaPages.map(({ path }) => path)
  )};
`;

  await fs.writeFile(OUTPUT, content);
  console.log(
    `  agent-routes.generated.js  (${STATIC_PATHS.length} static, ${coursePages.length} courses, ${provinciaPages.length} provincias)`
  );
};

generate()
  .then(() => console.log("Agent routes generated successfully."))
  .catch((err) => {
    console.error("Agent routes generation failed:", err);
    process.exit(1);
  });
